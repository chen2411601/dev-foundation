#!/usr/bin/env bash

# ==========================================
# 自动化系统健康巡检脚本 (System Health Check)
# ==========================================

echo "================ [1. 基础资源状态] ================"
echo "--- 内存使用情况 (Memory) ---"
free -h | awk 'NR<=2'

echo -e "\n--- 硬盘空间占用 (Disk) ---"
df -h / | awk 'NR<=2'

echo -e "\n================ [2. 内存消耗前 3 的进程] ================"
# 流水线：列出进程 -> 按内存排序 -> 截取前 4 行 (表头 + Top 3)
ps aux --sort=-%mem | head -n 4 | awk '{print $1, $2, $3, $4, $11}'

echo -e "\n================ [3. 当前监听的网络端口] ================"
# 查看有哪些服务正在对外开门
ss -tuln | head -n 10

echo -e "\n巡检完毕！系统运行正常。"